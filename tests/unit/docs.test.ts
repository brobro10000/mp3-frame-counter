/**
 * Exercise finite docs routing and fail-closed readiness with the real generated assets. Run after `npm run build`
 * through `node --test tests/unit/docs.test.ts`; temporary source/compiled layouts and loopback listeners are removed
 * after each case. No acceptance fixture, renderer mock or missing-output fallback supplies a passing resource.
 */
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { once } from "node:events";
import { cp, mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { Agent, request } from "node:http";
import type { ClientRequest, IncomingHttpHeaders } from "node:http";
import type { AddressInfo } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, test } from "node:test";
import type { TestContext } from "node:test";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createApiServer } from "../../server/src/http.ts";

const repository = fileURLToPath(new URL("../../", import.meta.url));
const publicResources = [
  ["/docs/", "index.html", "text/html"],
  ["/docs/openapi.yaml", "openapi.yaml", "application/yaml"],
  ["/docs/assets/redoc.js", "assets/redoc.js", "application/javascript"],
  ["/docs/assets/init.js", "assets/init.js", "application/javascript"],
  ["/docs/assets/docs.css", "assets/docs.css", "text/css"],
  ["/docs/assets/redoc-logo-mini.svg", "assets/redoc-logo-mini.svg", "image/svg+xml"],
] as const;

interface Reply {
  status: number;
  headers: IncomingHttpHeaders;
  body: Buffer;
}

async function start(context: TestContext): Promise<number> {
  const service = createApiServer();
  context.after(() => {
    service.server.closeAllConnections();
    return service.shutdown();
  });
  await service.listen(0, "127.0.0.1");
  return (service.server.address() as AddressInfo).port;
}

function collect(outgoing: ClientRequest): Promise<Reply> {
  return new Promise((resolve, reject) => {
    outgoing.once("error", reject);
    outgoing.once("response", (response) => {
      const chunks: Buffer[] = [];
      response.on("data", (chunk: Buffer) => chunks.push(chunk));
      response.once("error", reject);
      response.once("end", () => {
        resolve({ status: response.statusCode!, headers: response.headers, body: Buffer.concat(chunks) });
      });
    });
  });
}

async function send(port: number, path: string, method = "GET", headers: Record<string, string> = {}): Promise<Reply> {
  const outgoing = request({ hostname: "127.0.0.1", port, path, method, headers, agent: false, timeout: 3_000 });
  outgoing.once("timeout", () => outgoing.destroy(new Error("Documentation request timed out.")));
  const reply = collect(outgoing);
  outgoing.end();
  return reply;
}

function expectError(reply: Reply, status: number): void {
  assert.equal(reply.status, status);
  assert.match(reply.headers["content-type"] ?? "", /^application\/json(?:;|$)/);
  const value = JSON.parse(reply.body.toString("utf8"));
  assert.deepEqual(Object.keys(value), ["error"]);
  assert.equal(typeof value.error, "string");
  assert.ok(value.error.trim());
}

describe("Documentation serving and readiness", () => {
  test("every public resource serves generated bytes with query identity, media, HEAD and no-store", async (context) => {
    const port = await start(context);
    for (const [path, file, media] of publicResources) {
      const expected = await readFile(join(repository, "dist/docs", file));
      const reply = await send(port, `${path}?source=unit`);
      assert.equal(reply.status, 200);
      assert.equal(reply.headers["content-type"], `${media}; charset=utf-8`);
      assert.equal(reply.headers["content-length"], String(expected.length));
      assert.deepEqual(reply.body, expected);
      const head = await send(port, `${path}?source=head`, "HEAD");
      assert.equal(head.status, 200);
      assert.equal(head.body.length, 0);
      for (const response of [reply, head]) {
        assert.equal(response.headers["cache-control"], "no-store");
        assert.equal(response.headers["x-content-type-options"], "nosniff");
        assert.equal(response.headers["referrer-policy"], "no-referrer");
        assert.equal(response.headers["content-length"], String(expected.length));
        if (file === "openapi.yaml") {
          assert.equal(response.headers["content-disposition"], 'attachment; filename="openapi.yaml"');
        }
      }
      if (file === "assets/redoc.js" || file === "assets/redoc-logo-mini.svg") {
        assert.equal(
          createHash("sha256").update(reply.body).digest("hex"),
          file === "assets/redoc.js"
            ? "21ce5beb19818927f12e2db16e1a332e4f0eac5b8538012b6ecd048585b8cdbf"
            : "1dab4315f8de2177b2b2726b29e84a26314c69cd27d692228947c0058793d5a7",
        );
      }
    }
  });

  test("redirects are relative and known docs methods share a GET/HEAD-only decision", async (context) => {
    const port = await start(context);
    for (const method of ["GET", "HEAD"]) {
      const reply = await send(port, "/docs?ignored=1", method);
      assert.equal(reply.status, 308);
      assert.equal(reply.headers.location, "/docs/");
      assert.equal(reply.body.length, 0);
      assert.equal(reply.headers["cache-control"], "no-store");
    }
    for (const path of ["/docs", ...publicResources.map(([path]) => path)]) {
      for (const method of ["POST", "PUT", "PATCH", "OPTIONS", "DELETE"]) {
        const reply = await send(port, `${path}?ignored=1`, method);
        expectError(reply, 405);
        assert.equal(reply.headers.allow, "GET, HEAD");
      }
    }
  });

  test("unknown contained paths win over method, never expose retained files and keep HEAD empty", async (context) => {
    const port = await start(context);
    for (const path of [
      "/docs/unknown",
      "/docs/assets/",
      "/docs/assets/redoc.js.map",
      "/docs/retained/provenance.json",
      "/docs/%6fpenapi.yaml",
      "/docs/../healthz",
      "/docs/assets/../../index.html",
    ]) {
      for (const method of ["GET", "POST", "OPTIONS"]) {
        const reply = await send(port, `${path}?ignored=1`, method);
        expectError(reply, 404);
        assert.equal(reply.headers.allow, undefined);
        assert.equal(reply.headers["cache-control"], "no-store");
      }
      const head = await send(port, path, "HEAD");
      assert.equal(head.status, 404);
      assert.equal(head.body.length, 0);
    }
  });

  test("docs with oversized declarations answer before Continue beside both admitted uploads", async (context) => {
    const port = await start(context);
    const held: ClientRequest[] = [];
    const docsAgent = new Agent({ keepAlive: true });
    context.after(() => docsAgent.destroy());
    context.after(() => held.forEach((outgoing) => outgoing.destroy()));
    for (let index = 0; index < 2; index += 1) {
      const outgoing = request({
        hostname: "127.0.0.1",
        port,
        path: "/file-upload",
        method: "POST",
        headers: { "Content-Type": "audio/mpeg", "Content-Length": "1024", Expect: "100-continue" },
        agent: false,
      });
      held.push(outgoing);
      outgoing.on("error", () => {});
      const continued = once(outgoing, "continue", { signal: AbortSignal.timeout(2_000) });
      outgoing.flushHeaders();
      await continued;
    }
    for (const [method, path, status] of [
      ["GET", "/docs/", 200],
      ["HEAD", "/docs/openapi.yaml", 200],
      ["POST", "/docs/assets/init.js", 405],
      ["PUT", "/docs/unknown", 404],
    ] as const) {
      const outgoing = request({
        hostname: "127.0.0.1",
        port,
        path,
        method,
        headers: { "Content-Length": "20971521", Expect: "100-continue", Connection: "keep-alive" },
        agent: docsAgent,
        timeout: 2_000,
      });
      let continued = false;
      outgoing.on("continue", () => {
        continued = true;
      });
      outgoing.once("timeout", () => outgoing.destroy(new Error("Documentation awaited request bytes.")));
      const reply = collect(outgoing);
      const connected = once(outgoing, "socket", { signal: AbortSignal.timeout(2_000) });
      outgoing.flushHeaders();
      const [socket] = await connected;
      const closed = once(socket, "close", { signal: AbortSignal.timeout(2_000) });
      void closed.catch(() => {});
      try {
        const response = await reply;
        assert.equal(response.status, status);
        assert.equal(continued, false);
        assert.equal(response.headers.connection, "close");
        // The server must close without client assistance even after bypassing the upload body's idle timer.
        await closed;
      } finally {
        outgoing.destroy();
      }
    }
    expectError(await send(port, "/file-upload", "POST", { "Content-Type": "audio/mpeg" }), 503);
  });

  /** Isolate real generated output and normal module layouts so corrupt-output tests never mutate shared build files. */
  async function deployment(
    context: TestContext,
    layout: "source" | "compiled",
    includeAssets: boolean,
  ): Promise<string> {
    const directory = await mkdtemp(join(tmpdir(), "mp3-docs-readiness-"));
    context.after(() => rm(directory, { recursive: true, force: true }));
    await writeFile(join(directory, "package.json"), '{"type":"module"}\n');
    await symlink(join(repository, "node_modules"), join(directory, "node_modules"), "dir");
    const moduleDirectory = layout === "source" ? "server/src" : "dist";
    const extension = layout === "source" ? "ts" : "js";
    await mkdir(join(directory, moduleDirectory), { recursive: true });
    for (const name of ["http", "docs", "errors", "mp3"]) {
      const relative = `${moduleDirectory}/${name}.${extension}`;
      await cp(join(repository, relative), join(directory, relative));
    }
    if (includeAssets) {
      await mkdir(join(directory, "dist/docs/assets"), { recursive: true });
      for (const [, file] of publicResources) {
        await cp(join(repository, "dist/docs", file), join(directory, "dist/docs", file));
      }
    }
    return directory;
  }

  /** A fresh process imports normally, constructs synchronously and proves readiness before any listener exists. */
  function probe(directory: string, layout: "source" | "compiled", expected: "ready" | "rejected"): void {
    const module = pathToFileURL(join(directory, layout === "source" ? "server/src/http.ts" : "dist/http.js")).href;
    const operation =
      expected === "ready"
        ? `await service.listen(0, "127.0.0.1");
       assert.equal(service.server.listening, true);
       const reply = await fetch("http://127.0.0.1:" + service.server.address().port + "/docs/");
       assert.equal(reply.status, 200);
       assert.match(await reply.text(), /<!doctype html>/i);`
        : `await assert.rejects(service.listen(0, "127.0.0.1"));
       assert.equal(service.server.listening, false);
       assert.equal(service.server.address(), null);`;
    const child = spawnSync(
      process.execPath,
      [
        "--input-type=module",
        "--eval",
        `
    import assert from "node:assert/strict";
    import { createApiServer } from ${JSON.stringify(module)};
    const service = createApiServer();
    assert.equal(service.server.listening, false);
    try { ${operation} } finally {
      service.server.closeAllConnections();
      const closing = service.shutdown();
      assert.equal(service.shutdown(), closing);
      await closing;
    }
    assert.equal(service.server.listening, false);
  `,
      ],
      { cwd: tmpdir(), encoding: "utf8", timeout: 5_000, maxBuffer: 16_384 },
    );
    assert.equal(child.error, undefined, child.error?.message);
    assert.equal(child.status, 0, child.stderr);
  }

  test("source and compiled startup both require the real generated output before listening", async (context) => {
    for (const layout of ["source", "compiled"] as const) {
      for (const includeAssets of [false, true]) {
        await context.test(`${layout}: ${includeAssets ? "complete" : "missing"} generated output`, async (context) => {
          const directory = await deployment(context, layout, includeAssets);
          probe(directory, layout, includeAssets ? "ready" : "rejected");
        });
      }
    }
  });

  test("missing, malformed, oversized and substituted required assets fail compiled readiness", async (context) => {
    const changes = [
      async (root: string) => rm(join(root, "assets/init.js")),
      async (root: string) => writeFile(join(root, "index.html"), ""),
      async (root: string) => writeFile(join(root, "openapi.yaml"), '{"openapi":"3.1.0"}'),
      async (root: string) => writeFile(join(root, "assets/docs.css"), Buffer.alloc(262_145, 32)),
      async (root: string) => writeFile(join(root, "assets/redoc.js"), "window.Redoc = {};"),
      async (root: string) => writeFile(join(root, "assets/redoc-logo-mini.svg"), "<svg></svg>"),
      async (root: string) => writeFile(join(root, "assets/init.js"), Buffer.from([0xff])),
    ];
    for (const [index, change] of changes.entries()) {
      await context.test(`invalid resource ${index + 1}`, async (context) => {
        const directory = await deployment(context, "compiled", true);
        await change(join(directory, "dist/docs"));
        probe(directory, "compiled", "rejected");
      });
    }
  });
});
